"""Frozen text-only SigLIP 2 tower, pinned revision; no vision tower is loaded."""
import json
from pathlib import Path
import numpy as np
from .contract import TEXT_SPEC, canonical, normalize_text
from .storage import atomic_file


class TextEncoder:
    def __init__(self, device="cpu"):
        import torch
        from transformers import AutoConfig, AutoTokenizer, SiglipTextModel, Siglip2TextModel
        self.device = device
        self.tokenizer = AutoTokenizer.from_pretrained(TEXT_SPEC["model"], revision=TEXT_SPEC["revision"])
        # The pinned SigLIP 2 base checkpoint declares the original Siglip
        # architecture in its config. Select its actual text config instead of
        # constructing a Siglip2 tower with a multimodal config (hidden_size is
        # nested there). Neither branch instantiates a vision tower.
        config = AutoConfig.from_pretrained(TEXT_SPEC["model"], revision=TEXT_SPEC["revision"])
        text_config = config.text_config
        towers = {"siglip_text_model": SiglipTextModel, "siglip2_text_model": Siglip2TextModel}
        if text_config.model_type not in towers:
            raise ValueError("Unexpected text architecture in pinned checkpoint")
        tower = towers[text_config.model_type]
        self.model, info = tower.from_pretrained(TEXT_SPEC["model"], revision=TEXT_SPEC["revision"],
                                                config=text_config, output_loading_info=True)
        if info.get("missing_keys") or info.get("mismatched_keys"):
            raise ValueError("Frozen text tower has missing or incompatible weights")
        self.model = self.model.to(device).eval()
        self.model.requires_grad_(False)
        self.torch = torch

    def encode(self, texts):
        texts = [normalize_text(t) for t in texts]
        inputs = self.tokenizer(texts, padding="max_length", truncation=True,
                                max_length=TEXT_SPEC["max_length"], return_tensors="pt").to(self.device)
        with self.torch.inference_mode():
            vectors = self.model(**inputs).pooler_output
            return self.torch.nn.functional.normalize(vectors, dim=-1).cpu().numpy().astype(np.float32)

    def encode_tokens(self, texts, count=16):
        """Per-token final hidden states [B, count, 768] for cross-attention.

        Same tokenizer settings as ``encode`` (padding to 64); the first
        ``count`` positions are kept, padding included, identically at
        training and inference.
        """
        texts = [normalize_text(t) for t in texts]
        inputs = self.tokenizer(texts, padding="max_length", truncation=True,
                                max_length=TEXT_SPEC["max_length"], return_tensors="pt").to(self.device)
        with self.torch.inference_mode():
            hidden = self.model(**inputs).last_hidden_state[:, :count]
        return hidden.float().cpu().numpy().astype(np.float16)


TOKEN_SPEC = TEXT_SPEC | {"embedding": "SiglipTextModel.last_hidden_state[:, :16]", "tokens": 16}


PHRASE_VERSION = "label-phrases-1"


def label_phrases(label):
    """Natural phrasings of one dataset label, generated by fixed generic rules.

    Dataset names such as ``car_(automobile)`` are identifiers, not what a
    person types. Training on several clean phrasings narrows the gap between
    training labels and prompts. No synonym or translation table is involved;
    the frozen encoder alone carries meaning to other words and languages.
    """
    label = normalize_text(label)
    head, _, rest = label.partition("_(")
    head = " ".join(head.replace("_", " ").split())
    qualifier = " ".join(rest.rstrip(")").replace("_", " ").split())
    if not head:
        raise ValueError("Empty label")
    phrases = [head, f"a {head}", f"{head} moving"]
    if qualifier:
        phrases.append(f"{head} ({qualifier})")
    return list(dict.fromkeys(phrases))


def cache_phrase_embeddings(manifest_path, output, device="cpu"):
    """Embed every phrasing of every label; the first phrasing is the canonical one."""
    manifest = json.loads(Path(manifest_path).read_text(encoding="utf-8"))
    labels = sorted({r["normalized_label"] for r in manifest["clips"]})
    if not labels:
        raise ValueError("Empty dataset")
    phrases, owners = [], []
    for label in labels:
        for phrase in label_phrases(label):
            phrases.append(phrase)
            owners.append(label)
    encoder = TextEncoder(device)
    vectors = np.concatenate([encoder.encode(phrases[i:i+64]) for i in range(0, len(phrases), 64)])
    if vectors.shape != (len(phrases), TEXT_SPEC["dimension"]) or not np.isfinite(vectors).all():
        raise ValueError("Invalid phrase vectors")
    metadata = {"text_spec": TEXT_SPEC, "dataset_fingerprint": manifest["fingerprint"], "synthetic_encoder": False,
                "phrase_version": PHRASE_VERSION, "phrases": len(phrases), "labels": len(labels),
                "loaded_text_tower": type(encoder.model).__name__, "vision_tower_loaded": False}
    with atomic_file(output) as stream:
        np.savez_compressed(stream, phrases=np.array(phrases), labels=np.array(owners), embeddings=vectors,
                            metadata=np.array(canonical(metadata)))
    return metadata


def load_phrase_embeddings(path, dataset_fingerprint):
    with np.load(path, allow_pickle=False) as cache:
        metadata = json.loads(str(cache["metadata"]))
        if metadata["dataset_fingerprint"] != dataset_fingerprint or metadata["text_spec"] != TEXT_SPEC:
            raise ValueError("Phrase cache belongs to another dataset or text encoder")
        if metadata.get("synthetic_encoder") or metadata.get("phrase_version") != PHRASE_VERSION:
            raise ValueError("Phrase cache is synthetic or from another phrasing version")
        vectors = cache["embeddings"]
        if not np.isfinite(vectors).all():
            raise ValueError("Invalid phrase vectors")
        result = {}
        for label, vector in zip(cache["labels"].tolist(), vectors):
            result.setdefault(label, []).append(vector)
    return {label: np.stack(v) for label, v in result.items()}, metadata


def cache_embeddings(manifest_path, output, device="cpu", existing_cache=None):
    manifest = json.loads(Path(manifest_path).read_text(encoding="utf-8"))
    labels = sorted({r["normalized_label"] for r in manifest["clips"]})
    if not labels:
        raise ValueError("Empty dataset")
    previous = {}
    if existing_cache:
        with np.load(existing_cache, allow_pickle=False) as cache:
            old = json.loads(str(cache["metadata"]))
            if old["text_spec"] != TEXT_SPEC or old.get("synthetic_encoder"):
                raise ValueError("Only genuine embeddings from the same frozen text encoder can be reused")
            previous = dict(zip(cache["labels"].tolist(), cache["embeddings"]))
    missing = [label for label in labels if label not in previous]
    encoder = TextEncoder(device) if missing else None
    for first in range(0, len(missing), 32):
        batch = missing[first:first+32]
        previous.update(zip(batch, encoder.encode(batch)))
    vectors = np.stack([previous[label] for label in labels])
    if vectors.shape != (len(labels), TEXT_SPEC["dimension"]) or not np.isfinite(vectors).all():
        raise ValueError("Invalid cached text vectors")
    metadata = {"text_spec": TEXT_SPEC, "dataset_fingerprint": manifest["fingerprint"], "synthetic_encoder": False,
                "loaded_text_tower": type(encoder.model).__name__ if encoder else "reused pinned checkpoint text embeddings",
                "vision_tower_loaded": False}
    with atomic_file(output) as stream:
        np.savez_compressed(stream, labels=np.array(labels), embeddings=vectors, metadata=np.array(canonical(metadata)))
    return metadata

